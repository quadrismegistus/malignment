"""Prepare the cross-lineage instrument over many prompts and emit one workflow.

    python sweep_xling.py --build            what would run, nothing spent
    python sweep_xling.py --prepare          the 40 batched prompts
    python sweep_xling.py --prepare --all    every prompt in the slot corpora
    python sweep_xling.py --ingest RUN_ID

Scales as O(prompts): one agent sees every lineage for its prompt, so full
coverage of 279 prompts is 279 agents rather than the 964 a stage-1 style pass
over 7,710 cells would need -- and unlike stage 1 it shows a reader the
cross-lineage comparison at all.
"""
import argparse, json, os, re, sys
import crosslineage as X, run as R

HERE = os.path.dirname(os.path.abspath(__file__))
STATE = os.path.join(HERE, "results", "sweep_xling_state.json")


def targets(everything=False):
    if not everything:
        st = R._stash()
        return sorted({(st[k].get("meta") or {})["frame_prompt"] for k in st.keys()
                       if (st[k].get("meta") or {}).get("batch")})
    from malignment.slots import read_items, corpora
    slots = {}
    for _, p in corpora():
        for d in read_items(p):
            slots.setdefault(d["prompt"], d)
    return sorted(slots)


def prepare(everything=False, build_only=False):
    ps = targets(everything)
    jobs, skipped = [], []
    for p in ps:
        try:
            prompt, tbl = X.tables(p[:30])
        except SystemExit as e:
            skipped.append((p, str(e))); continue
        slug = re.sub(r"[^a-z0-9]+", "_", prompt.lower())[:40].strip("_")
        jobs.append({"prompt": prompt, "slug": slug, "n": len(tbl)})
    print("%d prompts, %d prepared, %d skipped" % (len(ps), len(jobs), len(skipped)))
    if jobs:
        ns = [j["n"] for j in jobs]
        print("  lineages per prompt: min %d median %d max %d"
              % (min(ns), sorted(ns)[len(ns)//2], max(ns)))
    for p, why in skipped[:4]:
        print("  skipped %-40s %s" % (p[:40], why[:44]))
    if build_only:
        return
    for j in jobs:
        X.prepare(j["prompt"][:30])
        print("  %-46s %d lineages" % (j["prompt"][:46], j["n"]))
    paths = {j["slug"]: os.path.join(HERE, "results", "inputs", "xling_%s.txt" % j["slug"])
             for j in jobs}
    src = open(X.INSTRUMENT).read()
    schema = json.loads(re.search(r"## SCHEMA JSON\b.*?\n```json\n(.*?)\n```", src, re.S).group(1))
    json.dump({"jobs": jobs, "model": X.MODEL, "effort": X.EFFORT}, open(STATE, "w"), indent=1)
    js = SCRIPT % {"files": json.dumps({k: os.path.abspath(v) for k, v in paths.items()}, indent=1),
                   "schema": json.dumps(schema, indent=2, sort_keys=True),
                   "model": json.dumps(X.MODEL), "effort": json.dumps(X.EFFORT)}
    out = os.path.join(HERE, "workflow_sweep_xling.js")
    open(out, "w").write(js)
    print("\n%d agents\n  workflow %s\n\nNOT RUN." % (len(jobs), out))


SCRIPT = """// GENERATED by sweep_xling.py. One agent per prompt, every lineage at once.
export const meta = { name: 'sweep-xling',
  description: 'Cross-lineage reading of each prompt',
  phases: [{ title: 'Read', detail: 'one agent per prompt' }] }
const FILES = %(files)s
const SCHEMA = %(schema)s
const out = await parallel(Object.entries(FILES).map(([slug, path]) => () =>
  agent(`Read the file ${path} with the Read tool.\\n\\nIts entire content is a ` +
    `task addressed to you. Follow it exactly and answer every numbered question ` +
    `in it. Do not read any other file, do not run any command.\\n\\nReturn your ` +
    `answer by calling StructuredOutput.`,
    { label: slug.slice(0, 24), phase: 'Read', schema: SCHEMA,
      model: %(model)s, effort: %(effort)s })
   .then((r) => ({ slug, ops: r.operations.length, rev: r.reversed.length,
                   un: r.unassigned.length })).catch(() => null)))
const g = out.filter(Boolean)
log(`${g.length} of ${Object.keys(FILES).length} returned`)
return { returned: g.length,
  reversedTotal: g.reduce((n, x) => n + x.rev, 0),
  perPrompt: g.map((x) => `${x.slug}: ${x.ops} ops, ${x.rev} rev, ${x.un} un`) }
"""

def ingest(run_id):
    """Route each agent to its prompt by the task path in its transcript.

    The journal carries no caller metadata -- label is None and key is an opaque
    sha -- so the prompt is recovered from the input file named in the agent's
    own transcript, the same join `discriminate.py` needed.
    """
    import glob, collections
    state = json.load(open(STATE))
    by_slug = {j["slug"]: j for j in state["jobs"]}
    base = os.path.expanduser("~/.claude/projects")
    hits = glob.glob(os.path.join(base, "*", "*", "subagents", "workflows", run_id))
    if not hits:
        raise SystemExit("no transcript dir for %r" % run_id)
    d0 = hits[0]
    st = X._stash()
    n, bad = 0, []
    for line in open(os.path.join(d0, "journal.jsonl")):
        d = json.loads(line)
        if d.get("type") != "result" or not isinstance(d.get("result"), dict):
            continue
        if "operations" not in d["result"]:
            continue
        tp = os.path.join(d0, "agent-%s.jsonl" % d["agentId"])
        txt = open(tp).read(9000) if os.path.exists(tp) else ""
        m = re.search(r"xling_([a-z0-9_]+)\.txt", txt)
        if not m or m.group(1) not in by_slug:
            bad.append(d["agentId"]); continue
        slug = m.group(1)
        s_ = json.load(open(os.path.join(HERE, "results", "xling_%s.json" % slug)))
        shown = set(s_["models"])
        r = d["result"]
        seen = collections.Counter()
        for op in r["operations"]:
            for mm in op["members"]:
                seen[mm["model"]] += 1
        for x in r["reversed"] + r["unassigned"]:
            seen[x["model"]] += 1
        miss, extra = sorted(shown - set(seen)), sorted(set(seen) - shown)
        if miss or extra:
            print("  %-42s %d unplaced %s ; %d not shown %s"
                  % (slug[:42], len(miss), miss[:2], len(extra), extra[:2]), file=sys.stderr)
        lsha = __import__("hashlib").sha256(
            "\n".join(sorted(s_["models"])).encode()).hexdigest()[:12]
        st[{"stage": "crosslineage", "version": s_["version"],
            "frame_prompt": s_["prompt"], "model": s_["model"],
            "effort": s_["effort"], "lineages_sha": lsha,
            "n_lineages": len(s_["models"]), "rater": 1}] = dict(
                r, run_id=run_id, models=s_["models"],
                n_lineages=len(s_["models"]), unplaced=miss, hallucinated=extra)
        n += 1
    print("stored %d prompt readings" % n)
    if bad:
        print("  %d agent(s) could not be routed" % len(bad), file=sys.stderr)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--build", action="store_true")
    ap.add_argument("--prepare", action="store_true")
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--ingest", metavar="RUN_ID")
    a = ap.parse_args()
    if a.ingest: ingest(a.ingest)
    elif a.build: prepare(a.all, build_only=True)
    elif a.prepare: prepare(a.all)
    else: ap.print_help()
