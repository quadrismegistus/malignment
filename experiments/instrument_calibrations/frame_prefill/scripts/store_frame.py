"""The frame effect on the STORE corpus, at 78 models instead of 9.

    .venv/bin/python -u scripts/store_frame.py            -> results/store_frame.json

The rest of this folder measured the frame on 22 hand-built stems across 9
roots, because that is what could be generated by hand. `twp_words_v4` now holds
framed cells -- `frame='prefill'`, 874 prompts, 78 models -- so the same
question can be asked on the campaign's own corpus at eight times the models.

**This does not reopen the frame policy.** README's DECISION stands: `raw` is
forced corpus-wide by definability, and `chat`, `prefill_bare`, `prefill_space`
and `prefill_instruct` stay retired. What the store adds is SIZE, on the one
condition that survived (`sys ""`, `user "Hi."`, stem prefilled), and the
population that makes the decomposition possible at all: 8 of the framed models
are BASES, so the frame can be measured with the weights held.

## THE FOUR QUANTITIES, AND WHY EACH NEEDS ITS OWN CELL

    ARM raw       base raw    -> aligned raw       the campaign's default
    ARM framed    base frmd   -> aligned frmd      the arm, frame held constant
    FRAME base    base raw    -> base frmd         the wrapper, WEIGHTS HELD
    FRAME aligned aligned raw -> aligned frmd
    BOTH          base raw    -> aligned frmd      what a cross-frame edge is

`BOTH` is what `movement_cells_v4_crossframe` holds, and on its own it cannot
say anything about alignment: it moves the weights AND the frame in one step.
`FRAME base` is the control that prices the frame half, and it is only available
because those 8 bases ship a template.

## THREE THINGS THIS FILE HAS TO GET RIGHT

**Query PER MODEL.** The all-models form of the admitted-mass aggregation asked
ClickHouse to spill 42 GB against 27 GB of temp disk and died. The aggregation
is identical per model; only the working set differs.

**Never pool `system_mode`.** 66 framed models carry `empty` and 12 carry
`default`, and [6557] ruled those non-poolable. Everything here is `empty`, and
the 12 `default` models are therefore NOT covered by any number this produces.

**Match prompts, and match them by TEXT.** 840 of the 874 framed prompts also
exist raw. Every comparison is restricted to the intersection per model, so a
frame difference cannot be a coverage difference.
"""

import collections
import json
import math
import os
import statistics as st
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.abspath(os.path.join(HERE, "..", "..", "..")))

from malignment import ch, roster                                    # noqa: E402

OUT = os.path.join(HERE, "results", "store_frame.json")
#: the store dedups the same way `twp_words_v4_best` does -- argMax on
#: (topup, prompt_cache, mtime) -- but that view also filters `frame=''`, so it
#: cannot be used here and the dedup is written out.
PICK = "argMax(p,(topup,prompt_cache,mtime))"


def js(p, q):
    """Jensen-Shannon divergence in bits between two word->mass maps."""
    out = 0.0
    for k in set(p) | set(q):
        a, b = p.get(k, 0.0), q.get(k, 0.0)
        mid = (a + b) / 2
        if a > 0:
            out += a * math.log2(a / mid) / 2
        if b > 0:
            out += b * math.log2(b / mid) / 2
    return out


def dists(model):
    """-> {(frame, prompt): {word: p}} for one model, `system_mode` empty only."""
    rows = ch.query(
        "SELECT frame, prompt, word, %s p FROM twp_words_v4 "
        "WHERE model='%s' AND system_mode IN ('','empty') "
        "GROUP BY frame,prompt,word" % (PICK, model))
    d = collections.defaultdict(dict)
    for r in rows:
        d[(r["frame"], r["prompt"])][r["word"]] = float(r["p"])
    return d


def matched(d):
    return {p for f, p in d if f == ""} & {p for f, p in d if f == "prefill"}


def crossframe():
    """`raw->raw` against `raw->framed` per lineage, from malign's views.

    Cheap -- both are precomputed cell views ([6563], commit 8801de9) -- so it
    runs first and is written even if the per-model pass is interrupted.
    `movement_cells_v4` was pooling raw and framed rows until that commit added
    `WHERE frame_base='' AND frame_aligned=''`; without the fix this comparison
    would be the same population against itself.
    """
    m = roster.endpoints()
    m = m[0] if isinstance(m, tuple) else m
    ep = set(m.items())
    rr = {(x["base"], x["aligned"], x["prompt"]): float(x["js_total"])
          for x in ch.query("SELECT base, aligned, prompt, js_total "
                            "FROM movement_cells_v4 WHERE rule='canonical'")}
    by = collections.defaultdict(list)
    for x in ch.query("SELECT base, aligned, prompt, js_total "
                      "FROM movement_cells_v4_crossframe "
                      "WHERE rule='canonical' AND system_mode_aligned='empty'"):
        k = (x["base"], x["aligned"])
        kk = (x["base"], x["aligned"], x["prompt"])
        if k in ep and kk in rr:
            by[k].append((rr[kk], float(x["js_total"])))
    out = []
    for (b, a), v in by.items():
        out.append(dict(base=b, aligned=a, n_prompts=len(v),
                        raw_raw=st.median([x[0] for x in v]),
                        raw_framed=st.median([x[1] for x in v])))
    return out


def main():
    m = roster.endpoints()
    m = m[0] if isinstance(m, tuple) else m
    bases, aligned = set(m), set(m.values())
    framed = [r["model"] for r in ch.query(
        "SELECT DISTINCT model FROM twp_words_v4 WHERE frame='prefill' ORDER BY model")]
    print("%d models carry framed cells" % len(framed), flush=True)

    out = {"within": [], "two_by_two": [], "crossframe": crossframe()}
    cf = out["crossframe"]
    up = sum(1 for x in cf if x["raw_framed"] > x["raw_raw"])
    print("CROSS-FRAME larger in %d of %d lineages | median ratio %.2fx"
          % (up, len(cf), st.median([x["raw_framed"] / x["raw_raw"] for x in cf])),
          flush=True)
    cache = {}
    for mo in framed:
        d = dists(mo)
        pr = matched(d)
        if not pr:
            continue
        arm = "base" if mo in bases else ("aligned" if mo in aligned else "other")
        rec = dict(model=mo, arm=arm, n_prompts=len(pr),
                   js=st.median([js(d[("", p)], d[("prefill", p)]) for p in pr]),
                   #: ADMITTED MASS, not entropy. If a framed model scatters onto
                   #: subword junk the recorded WORDS stay clean and the MASS
                   #: leaves -- entropy over what survived would look fine.
                   mass_raw=st.median([sum(d[("", p)].values()) for p in pr]),
                   mass_frmd=st.median([sum(d[("prefill", p)].values()) for p in pr]))
        out["within"].append(rec)
        if mo in bases or mo in aligned:
            cache[mo] = d
        print("  %-44s %-8s js %.4f  mass %.3f -> %.3f"
              % (mo.split("/")[-1][:44], arm, rec["js"],
                 rec["mass_raw"], rec["mass_frmd"]), flush=True)

    for b, a in m.items():
        if b not in cache or a not in cache:
            continue
        B, A = cache[b], cache[a]
        pr = matched(B) & matched(A)
        if not pr:
            continue
        out["two_by_two"].append(dict(
            base=b, aligned=a, n_prompts=len(pr),
            arm_raw=st.median([js(B[("", p)], A[("", p)]) for p in pr]),
            arm_framed=st.median([js(B[("prefill", p)], A[("prefill", p)]) for p in pr]),
            frame_base=st.median([js(B[("", p)], B[("prefill", p)]) for p in pr]),
            frame_aligned=st.median([js(A[("", p)], A[("prefill", p)]) for p in pr]),
            both=st.median([js(B[("", p)], A[("prefill", p)]) for p in pr])))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    json.dump(out, open(OUT, "w"), indent=1)

    print()
    for arm in ("base", "aligned", "other"):
        v = [x for x in out["within"] if x["arm"] == arm]
        if v:
            print("FRAME ALONE  %-8s n=%2d  median js %.4f  admitted mass %.3f -> %.3f"
                  % (arm, len(v), st.median([x["js"] for x in v]),
                     st.median([x["mass_raw"] for x in v]),
                     st.median([x["mass_frmd"] for x in v])))
    t = out["two_by_two"]
    if t:
        print()
        print("THE 2x2 over %d pairs with all four cells:" % len(t))
        for k in ("arm_raw", "arm_framed", "frame_base", "frame_aligned", "both"):
            print("   %-14s %.4f" % (k, st.median([x[k] for x in t])))
    print("-> %s" % OUT)


if __name__ == "__main__":
    main()
