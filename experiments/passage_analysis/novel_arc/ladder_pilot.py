"""Generate passages for every rung of a post-training ladder, one stem.

    .venv-tf457/bin/python .../ladder_pilot.py --ladder olmo-tiny --n 150
    .venv-tf457/bin/python .../ladder_pilot.py --ladder olmo-3 --n 60

**RUN THIS IN `.venv-tf457`.** Every OLMo node in `roster/models/models.yaml`
carries `env.profile: tf457` because transformers 5.4.0 raises
`TypeError: Field 'tie_word_embeddings' expected int, got bool` on their config
and 4.57.1 does not. Observed here on `Olmo-3-1025-7B` before switching.

## THE QUESTION: DOES THE SHIFT HAPPEN AT SFT OR AT DPO?

`novel_arc` established that alignment moves fiction ~56 years back on RH's
abstraction axis and past every period on interiority. Both are TWO-POINT
contrasts, base against aligned, which can say THAT post-training moves prose
but not WHICH step. Findings U established that SFT does the cutting for
displacement; if abstraction moves at SFT too, the two are one mechanism, and
RH's *Generative Formalism* framing -- instruction-tuning as an aesthetic side
effect of helpfulness -- covers both. If it waits for DPO, it is preference
optimisation and the story is about rater taste instead.

The store has no isolated SFT rung, which is why `experiments/TODO.md` files
this as blocked. **The CHECKPOINTS are all local** -- the blocker was only ever
the passages.

## EVERY ARM IS GENERATED HERE, AND THE STORE IS NOT THE CONTROL

The same trap `generation_provenance/frame_pilot.py` documents: the f11_l2
corpus was generated with **vLLM** and `Checkpoint.generate` runs **HF
transformers**, which sample differently at the same nominal temperature (vLLM
REPLACES the checkpoint's generation_config, HF MERGES it). So a rung compared
against the store's existing passages would differ by rung OR by engine. Every
rung here is generated by the same code, on the same device, in one run --
including the base and the released aligned endpoint, which the store already
holds and which are regenerated anyway.

## ONE STEM, AND WHAT THAT BOUNDS

Stem is the largest variance component in this corpus (ICC by stem 0.417-0.433
for API models), so N passages of ONE stem estimates the ladder effect FOR THAT
SCENE and cannot generalise across stems. That is the same limit `frame_pilot`
carries and the same reason it exists: a pilot for the machinery and a first
read on magnitude, not a powered design.

**AND THE POWER IS THIN EVEN FOR ONE SCENE.** Passage-level SD on
`rh_absconc_median` is roughly 0.4, so n=150 gives SE ~0.033 per rung. The
base-to-aligned gap for `olmo-tiny` is 0.2595 -- comfortably resolved -- but the
gap for `olmo-3` is 0.068, about two SE at n=60. The 1B ladder is the one that
can carry a verdict; the 7B ladder is a direction read.

## THE STASH IS THE RECORD

Passages land in `$MALIGNMENT_DATA/generations/<model>/<host>/` with the whole
condition in the key. This writes no results file; score it with
`ladder_pilot_score.py`, which runs in the LLTK venv because the scorer needs
`lltk.tools.constants` for the modernizer.
"""

import argparse, os, statistics, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(HERE, "..", "..", "..")))

#: the released endpoint is included so the ladder has its far end measured on
#: the same engine as its rungs, not inherited from the vLLM store.
LADDERS = {
    "olmo-tiny": ["allenai/OLMo-2-0425-1B",
                  "allenai/OLMo-2-0425-1B-SFT",
                  "allenai/OLMo-2-0425-1B-DPO",
                  "allenai/OLMo-2-0425-1B-Instruct"],
    #: one base, TWO branches. Think and Instruct share `Olmo-3-1025-7B`, so the
    #: two post-training recipes are comparable against a common origin -- there
    #: is no separate "think base" and none is needed.
    "olmo-3": ["allenai/Olmo-3-1025-7B",
               "allenai/Olmo-3-7B-Instruct-SFT",
               "allenai/Olmo-3-7B-Instruct-DPO",
               "allenai/Olmo-3-7B-Think-SFT",
               "allenai/Olmo-3-7B-Think-DPO"],
}
#: an f11_l2 stem with 134 passages already in the corpus, so the scene is one
#: the store has seen many models continue.
#: THE FRAME IS NOT FREE, AND `raw` IS NOT NEUTRAL FOR EVERY RUNG.
#:
#: `raw` (template=False) is the corpus's own condition and the right one for a
#: base model. It is OUT OF DISTRIBUTION for a reasoning-SFT rung, which was
#: trained on chat-templated traces: measured here, `Olmo-3-7B-Think-SFT` under
#: `raw` fails a bare ASCII-share screen on **40% of passages against base's
#: 5%**, and produces `"the Decompiler... cookie monster gone vikings"` among
#: the survivors. A -0.54 abstraction shift measured under those conditions is
#: not an abstraction finding.
#:
#: `prefill` puts the stem in a prefilled ASSISTANT turn, which `generate.render`
#: documents as "the only chat-mode position with a word slot in it". Its two
#: companions are deliberate, not defaults:
#:   system=""      ASSERTS an empty system, OVERRIDING the template's persona.
#:                  Distinct from passing none -- conditions.py measured a
#:                  2,500x swing on one stem across default/empty/persona.
#:   user_msg="Hi." the PRESENCE CONTROL. Semantically empty on purpose, so the
#:                  comparison isolates instruction CONTENT rather than the user
#:                  turn merely being non-empty; an empty turn leaves 13.9% of
#:                  mass on fill punctuation and any contentful turn collapses it.
#:
#: A base model has no chat template and will REFUSE this frame. That refusal is
#: the point and is printed, not swallowed: there is no single frame that is
#: in-distribution for both a base model and a reasoning rung, so the ladder
#: cannot be measured end to end under one condition.
FRAMES = {
    "raw": dict(template=False),
    "prefill": dict(prefill=True, system="", user_msg="Hi."),
}

STEM = "He was beautiful and disgusting and she wanted to"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--ladder", default="olmo-tiny", choices=sorted(LADDERS))
    ap.add_argument("--models", nargs="*")
    ap.add_argument("--n", type=int, default=150)
    ap.add_argument("--stem", default=STEM)
    ap.add_argument("--seed", type=int, default=20260822)
    ap.add_argument("--frame", default="raw", choices=("raw", "prefill"))
    a = ap.parse_args(argv)
    from malignment import Checkpoint

    models = a.models or LADDERS[a.ladder]
    #: print the RESOLVED list, not `--ladder`. With `--models` given, the
    #: ladder name is stale and the banner said "ladder olmo-tiny" over a run
    #: of smol3 checkpoints -- a log that misidentifies its own population.
    print("%d rungs | frame %s | stem %r | n=%d each\n  %s"
          % (len(models), a.frame, a.stem[:44], a.n,
             "\n  ".join(m for m in models)), flush=True)
    t0 = time.time()
    for i, m in enumerate(models, 1):
        t = time.time()
        ck = Checkpoint(m)
        try:
            ld = ck.load()
        except Exception as e:
            #: SAY IT and continue. A rung that will not load is a rung the
            #: ladder is missing, and a silent gap would read as a completed
            #: ladder with one fewer step.
            print("  [%d/%d] %-42s LOAD FAILED: %s"
                  % (i, len(models), m.split("/")[-1], str(e)[:120]), flush=True)
            continue
        try:
            ps = ck.generate(a.stem, n=a.n, seed=a.seed, loaded=ld, **FRAMES[a.frame])
        except Exception as e:
            #: a template REFUSAL is a property of the rung, not a crash. A base
            #: model has no chat template, so the prefill frame is unavailable
            #: to it -- which is the asymmetry this frame exists to expose, and
            #: it belongs in the output rather than in a traceback.
            print("  [%d/%d] %-42s FRAME REFUSED: %s"
                  % (i, len(models), m.split("/")[-1], str(e)[:110]), flush=True)
            continue
        print("  [%d/%d] %-42s %3d passages  %5.1fs  median %d new tokens"
              % (i, len(models), m.split("/")[-1], len(ps), time.time() - t,
                 statistics.median(p.n_new_tokens for p in ps)), flush=True)
        del ld
    print("-> generations stash, %.1f min total" % ((time.time() - t0) / 60))


if __name__ == "__main__":
    main()
