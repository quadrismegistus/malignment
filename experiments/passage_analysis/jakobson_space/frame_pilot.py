"""Pilot: does the API system prompt move drift? One stem, a few small models.

    python .../frame_pilot.py --model HuggingFaceTB/SmolLM2-360M-Instruct
    python .../frame_pilot.py --model X --n 100 --stem-idx 0

Writes into the shared generations stash via `Checkpoint.generate`, so a rerun
resumes rather than repeats and two conditions of one model share nothing but
the model.

## BOTH ARMS ARE GENERATED HERE, AND THE STORE'S RAW PASSAGES ARE NOT THE CONTROL

The obvious pilot compares new API-framed generations against the raw passages
already in `quadrants.csv`. That comparison is confounded: the f11_l2 corpus was
generated with **vLLM** (its spec records `engine` and `engine_version` per row)
and `Checkpoint.generate` runs **HF transformers**. Sampling differs between
engines at the same nominal temperature -- vLLM REPLACES the checkpoint's
generation_config where HF MERGES it, which is the reason that spec pins every
decoder field by name.

So a difference between the two would be frame OR engine and nothing here could
separate them. Both arms are generated by the same code, on the same device, in
the same run.

    raw    template=False, no system, no user turn -- the corpus's condition
    api    system = the exact string generate_task.py sent to the API models

## THE STASH IS THE RECORD AND THERE IS NO SECOND COPY

Every passage lands in `$MALIGNMENT_DATA/generations/<model>/<host>/` with its
whole condition in the key -- model, prompt, frame, the system prompt IN FULL,
the resolved decoder, seed, sample_idx. So this writes no results file. Re-run it
and it resumes; read it back with `ck.generations(frame="raw")`.

## ONE STEM, WHICH BOUNDS WHAT THIS CAN SAY

100 passages of ONE stem is 100 draws from one scene, so it estimates the frame
effect FOR THAT SCENE and cannot generalise across stems -- stem is the largest
variance component in this corpus (ICC by stem 0.417-0.433 for API models). This
is a pilot for the machinery and a first read on magnitude; the powered design
in `frame_eligibility.py` spreads the same budget over ~100 stems instead.

Reported with a bootstrap CI over passages, which is the right interval for
"this stem, this model" and would be the wrong one for any claim about models.
"""

import argparse, json, os, statistics, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(HERE, "..", "..", "..")))

#: the exact string the API models were generated behind. Imported, never
#: retyped -- a pilot testing a frame must test THE frame.
from generate_task import SYSTEM_PROMPT          # noqa: E402


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True)
    ap.add_argument("--n", type=int, default=100)
    ap.add_argument("--stem", default="She was ugly and misshapen and she wanted to")
    ap.add_argument("--seed", type=int, default=20260821)
    a = ap.parse_args(argv)
    from malignment import Checkpoint

    ck = Checkpoint(a.model)
    t0 = time.time()
    print("%s | stem %r | n=%d per arm" % (a.model, a.stem[:44], a.n), flush=True)

    #: ONE LOAD FOR BOTH ARMS. `generate` frees what it loads, so loading here
    #: and passing it down is the difference between one load and two.
    ld = ck.load()
    print("  loaded on %s in %.1fs" % (ld.dev, ld.load_s), flush=True)
    out = {}
    for arm, kw in (("raw", dict(template=False)),
                    ("api", dict(system=SYSTEM_PROMPT))):
        t = time.time()
        ps = ck.generate(a.stem, n=a.n, seed=a.seed, loaded=ld, **kw)
        out[arm] = [p._asdict() for p in ps]
        n_new = sum(1 for p in ps if p.n_new_tokens)
        print("  %-4s %3d passages, %5.1fs, median %d new tokens, finish %s"
              % (arm, len(ps), time.time() - t,
                 statistics.median(p.n_new_tokens for p in ps),
                 {f: sum(1 for p in ps if p.finish == f)
                  for f in {p.finish for p in ps}}), flush=True)

    #: **NO SIDE FILE.** `Checkpoint.generate` already wrote every passage to
    #: the generations stash, with its full condition in the key. Writing a
    #: JSON beside it would be a second store to keep in step, and two stores
    #: that can disagree eventually do. Read them back with
    #: `ck.generations(prompt=..., frame=...)`.
    print("  -> generations stash: %s  (%.1fs total)"
          % (ck.gen_dir(), time.time() - t0), flush=True)


if __name__ == "__main__":
    main()
