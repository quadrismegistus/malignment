"""The findings index in README.md, DERIVED from each folder's own frontmatter.

    python experiments/index.py --check    exit 1 if any README cannot supply a row
    python experiments/index.py --write    rewrite the block between the markers
    python experiments/index.py            print what --write would insert

## WHY THIS IS GENERATED AND NOT WRITTEN

`LAYOUT.md` carries the rule this exists to keep: **the finding lives in the
question's README, and nowhere else.** A number in two files is a number that
will disagree with itself, and the campaign has paid for that twice -- v1 kept 46
findings in a separate directory and 42 were cited by nothing, and four archive
artifacts each defined "the population" differently.

RH asked for a summary of every finding in one place. Those two things are only
compatible if the summary is a VIEW rather than a COPY. So every row here is read
out of the folder's own frontmatter at generation time. Edit a folder's
`headline:` and the index changes; edit the index and the next `--write` reverts
it. There is no second copy to drift.

**The drift is not hypothetical and the rate is known.** On 2026-09-02 an audit
of `passage_analysis/README.md` -- a HAND-WRITTEN index of eleven folders, by
someone who had read all eleven -- found four entries wrong or stale after about
a week: a third-party result reported as an open gap, a status line reading
COMPLETE over a folder whose own file said RUN, a four-finding folder summarised
as a status, and a file count off by eight. At 69 folders that rate makes a
hand-written summary wrong on arrival.

## WHY IT REFUSES RATHER THAN SKIPS

`--check` fails on a README that cannot supply a row. The alternative -- drop it
quietly and generate the rest -- produces an index that looks complete and is
not, which is worse than no index: a reader cannot tell a folder that has no
finding from a folder whose frontmatter is broken.

That failure has already happened here. `displacement/norm_change/README.md`
carried a well-formed-looking block whose `headline:` contained an unquoted
colon, so YAML read it as a nested mapping and the whole file failed to parse.
Nothing reported it, because nothing was parsing it. It sat that way for months
in a folder carrying one of the campaign's headline results.

## THE EXCLUSIONS ARE NAMED, NOT INFERRED

`figures/` and `results/` READMEs describe a directory of outputs, not a
question, and `LAYOUT.md` and this file's own README are not questions either.
They are listed in EXCLUDE by path rather than detected by a heuristic, because a
heuristic that silently drops a folder is the same defect as skipping a broken
one.
"""
import argparse
import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
BEGIN = "<!-- INDEX:BEGIN -- generated by index.py, do not edit by hand -->"
END = "<!-- INDEX:END -->"

#: named, never inferred. See the module docstring.
EXCLUDE = {
    "README.md",
    "slot_ratings/identity/figures/README.md",
    "slot_ratings/institutional/figures/README.md",
    "slot_ratings/sexual/figures/README.md",
    "slot_ratings/results/long/README.md",
}

#: subjects first, then the class axes. Within a group, `kind: subject` floats to
#: the top because it is the group's own index and the rest are its members.
ORDER = ["displacement", "passage_analysis", "slot_ratings", "division_of_labour",
         "emergence", "posttraining_corpus_analysis", "instrument_calibrations",
         "exploratory"]


def orphan_producers():
    """-> dirs holding a producer and NO README.

    **The first version of this file could not see them at all**, because it
    walked only directories that already had a README -- so the one state it
    most needed to report, an experiment with code and no written claim, was
    invisible to it by construction. `instrument_calibrations/frame_pilot/` was
    sitting in exactly that state and the checker passed over it in silence.

    A check whose blind spot is the defect it exists to find is not a weaker
    check, it is a check that cannot fire.

    **Bounded by DEPTH, not by a name blacklist.** The first working version
    reported eleven directories, ten of them `scripts/`, `figures/`, `archive/`
    and `tasks/` sitting inside experiments that already have a README and are
    covered by it. The obvious fix -- skip those four names -- is the same
    heuristic this module's docstring rejects for EXCLUDE: it silently passes
    over a real experiment that happens to be called `figures`, and it needs
    extending every time someone invents a directory name.

    LAYOUT.md caps nesting at `<subject>/<question>`, so anything deeper than
    two components is a helper directory by construction. That is a structural
    rule with no list to maintain, and a folder that violates it has a layout
    problem this checker is not the right place to report.
    """
    out = []
    for root, dirs, files in os.walk(HERE):
        dirs[:] = [d for d in dirs if d not in ("__pycache__", ".git")]
        if root == HERE or "README.md" in files:
            continue
        rel = os.path.relpath(root, HERE)
        if rel.count(os.sep) > 1:          #: deeper than <subject>/<question>
            continue
        if any(f.endswith(".py") for f in files):
            out.append(rel)
    return sorted(out)


def readmes():
    """-> [(relpath, frontmatter_dict_or_None, error_or_None)], sorted."""
    out = []
    for root, dirs, files in os.walk(HERE):
        dirs[:] = [d for d in dirs if d not in ("__pycache__", ".git")]
        if "README.md" not in files:
            continue
        rel = os.path.relpath(os.path.join(root, "README.md"), HERE)
        if rel in EXCLUDE:
            continue
        text = open(os.path.join(root, "README.md"), encoding="utf-8").read()
        if not text.startswith("---"):
            out.append((rel, None, "no frontmatter"))
            continue
        try:
            d = yaml.safe_load(text.split("---", 2)[1])
        except Exception as e:
            out.append((rel, None, "unparseable: %s" % str(e).split("\n")[0]))
            continue
        if not isinstance(d, dict):
            out.append((rel, None, "frontmatter is not a mapping"))
            continue
        out.append((rel, d, None))
    return sorted(out)


def first_sentence(v):
    """-> the status's leading sentence, with a marker if anything was dropped.

    `displacement_taxonomy`'s status is a 90-word paragraph naming its full
    design; rendered whole it buries every other row on the page. So the index
    shows the leading sentence.

    **The `[...]` is not decoration.** Truncating silently is how a summary
    starts asserting something narrower than its source -- the reader cannot
    tell a one-sentence status from the first sentence of six. The marker says
    "there is more in the file", which is the only honest form of a cut.
    """
    s = str(v).strip().replace("\n", " ")
    for i in range(len(s) - 1):
        #: a sentence ends at '. ' -- but not inside 2026-08-24, p=0.03, or 1.4x
        if s[i] == "." and s[i + 1] == " " and not s[i - 1].isdigit():
            s = s[:i + 1] + " [...]"
            break
    #: BACKSTOP. The digit guard above means a status whose first sentence ends
    #: in a date -- "RUN 2026-08-30. 50 endpoint lineages, ..." -- never splits,
    #: because the character before the period is a digit. Most such statuses are
    #: short and fine whole, but the rule cannot GUARANTEE that, and one folder's
    #: status is a 90-word paragraph. A soft rule with no hard bound is a rule
    #: that holds until the first case it does not.
    if len(s) > 160:
        cut = s[:160].rsplit(" ", 1)[0]
        s = cut.rstrip(",;:") + " [...]"
    return s


def check(rows):
    """-> list of complaints. A row that cannot be generated is an ERROR."""
    bad = ["%-58s has a producer and NO README" % o for o in orphan_producers()]
    for rel, d, err in rows:
        if err:
            bad.append("%-58s %s" % (rel, err))
            continue
        for k in ("status", "headline"):
            if not d.get(k):
                bad.append("%-58s missing `%s:`" % (rel, k))
        if d.get("kind") not in ("subject", "question", "calibration"):
            bad.append("%-58s `kind:` is %r, want subject|question|calibration"
                       % (rel, d.get("kind")))
    return bad


def render(rows):
    groups = {}
    for rel, d, err in rows:
        if err or not d:
            continue
        top = rel.split("/")[0] if "/" in rel else rel
        groups.setdefault(top, []).append((rel, d))

    out = [BEGIN, ""]
    for top in ORDER + sorted(k for k in groups if k not in ORDER):
        if top not in groups:
            continue
        members = groups[top]
        #: the subject's own README is the group blurb, not a row in it
        subj = [(r, d) for r, d in members if d.get("kind") == "subject"
                and r.count("/") == 1]
        rest = [(r, d) for r, d in members if (r, d) not in subj]
        out.append("### %s" % top)
        out.append("")
        for _, d in subj:
            q = d.get("question")
            if q:
                out.append("*%s*" % str(q).strip().rstrip("."))
                out.append("")
        for rel, d in sorted(rest):
            name = os.path.dirname(rel) or rel
            short = name.split("/")[-1]
            out.append("- **[`%s/`](%s)** -- `%s`  "
                       % (short, rel, first_sentence(d["status"])))
            out.append("  %s" % str(d["headline"]).strip().replace("\n", " "))
        out.append("")
    out.append(END)
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args(argv)

    rows = readmes()
    bad = check(rows)

    if a.check or bad:
        if bad:
            print("%d README(s) cannot supply an index row:\n" % len(bad))
            print("\n".join("  " + b for b in bad))
            print("\nRefusing rather than skipping: an index that silently drops "
                  "a folder\nlooks complete and is not. See index.py's docstring.")
            return 1
        print("all %d READMEs supply status, headline and kind." % len(rows))
        return 0

    body = render(rows)
    if not a.write:
        print(body)
        return 0

    p = os.path.join(HERE, "README.md")
    s = open(p, encoding="utf-8").read()
    if BEGIN not in s or END not in s:
        print("markers not found in README.md; add:\n%s\n%s" % (BEGIN, END))
        return 1
    pre, rest = s.split(BEGIN, 1)
    _, post = rest.split(END, 1)
    open(p, "w", encoding="utf-8").write(pre + body + post)
    print("wrote %d rows into README.md" % sum(
        1 for _, d, e in rows if not e and d.get("kind") != "subject"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
